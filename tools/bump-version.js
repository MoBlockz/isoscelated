// Run before every publish: node tools/bump-version.js
// Writes a new version number into version.json + js/version.js and adds ?v=<version> to every script in index.html,
// so phones/iPads/home-screen apps always download the new files instead of using an old saved copy.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const d = new Date(), pad = n => String(n).padStart(2, '0');
const v = `${d.getFullYear()}.${pad(d.getMonth() + 1)}.${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}`;
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({ v }) + '\n');
fs.writeFileSync(path.join(root, 'js', 'version.js'), `// generated by tools/bump-version.js\nwindow.ISO_VERSION = '${v}';\n`);
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = html.replace(/<script src="js\/([a-z0-9-]+)\.js(\?v=[^"]*)?"><\/script>/g, (m, name) => `<script src="js/${name}.js?v=${v}"></script>`);
if (!html.includes('js/version.js')) html = html.replace('<script src="js/filter.js', `<script src="js/version.js?v=${v}"></script>\n<script src="js/filter.js`);
fs.writeFileSync(path.join(root, 'index.html'), html);
console.log('version', v);
